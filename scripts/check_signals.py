"""Check the detectors against real candles: for each signal type, take recent real examples and print the numbers
behind them, recomputed from the raw candles, so a person can confirm them on any chart; then count how often each
type fires per 100 candles, to spot a noisy detector. Writes Markdown to stdout.

    python scripts/check_signals.py BTC ETH SOL XRP DOGE > docs/detector-checks.md"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scanner import indicators as ind          # noqa: E402
from scanner import signals as S               # noqa: E402
from scanner import sources                    # noqa: E402

TFS = ("1h", "4h", "1d")


def evidence(s: S.Signal, bars: list[S.Bar]) -> str:
    i = s.index
    b = bars[i]
    if s.kind.startswith("rsi"):
        r = ind.rsi([x.c for x in bars])
        return f"RSI before {r[i - 1]:.1f} → at the signal {r[i]:.1f}"
    if s.kind.startswith("volume"):
        avg = sum(x.v for x in bars[i - 20:i]) / 20
        return f"volume {b.v:,.0f} vs 20-candle average {avg:,.0f} = {b.v / avg:.2f}×; open {S.fmt(b.o)} close {S.fmt(b.c)}"
    if s.kind.startswith("range"):
        hi = max(x.h for x in bars[i - 30:i])
        lo = min(x.l for x in bars[i - 30:i])
        return f"close {S.fmt(b.c)}; previous 30 days high {S.fmt(hi)}, low {S.fmt(lo)}"
    if s.kind in ("golden-cross", "death-cross"):
        f, sl = ind.ema([x.c for x in bars], 50), ind.ema([x.c for x in bars], 200)
        return f"EMA50 − EMA200: before {f[i - 1] - sl[i - 1]:+.4g}, at the signal {f[i] - sl[i]:+.4g}"
    if "structure" in s.kind:
        a = ind.atr([x.h for x in bars], [x.l for x in bars], [x.c for x in bars])
        return (f"close {S.fmt(b.c)} vs swing level {S.fmt(s.extra['level'])} "
                f"(margin {abs(b.c - s.extra['level']) / (a[i] or 1):.2f} ATR; needs ≥ {S.STRUCT_MARGIN_ATR})")
    if s.kind.startswith("double"):
        j = next(k for k, x in enumerate(bars) if x.t == s.extra["broke"])
        p1 = next(x for x in bars if x.t == s.extra["first"])
        p2 = next(x for x in bars if x.t == s.extra["second"])
        ext = (p1.h, p2.h) if s.kind == "double-top" else (p1.l, p2.l)
        return (f"peaks {S.fmt(ext[0])} / {S.fmt(ext[1])} ({abs(ext[0] - ext[1]) / max(ext) * 100:.2f}% apart), "
                f"neckline {S.fmt(s.extra['neckline'])}, breaking close {S.fmt(bars[j].c)} at {S.bar_time(bars[j].t)}")
    return ""


def main(coins: list[str]) -> None:
    src, _ = sources.pick(log=lambda *_: None)
    print(f"# Detector checks on real candles\n\nSource: {src.name}, closed candles only. Generated by "
          f"`scripts/check_signals.py`. Each example's numbers are recomputed from the raw candles; open the same coin, "
          f"timeframe and candle time on any chart to compare.\n")
    freq: Counter = Counter()
    bars_total: Counter = Counter()
    examples: dict[str, list[str]] = {}
    for coin in coins:
        for tf in TFS:
            bars = src.klines(coin + "USDT" if src.name in ("binance", "mexc") else coin, tf, 400)
            sigs = S.scan(bars, tf)
            bars_total[tf] += len(bars)
            for s in sigs:
                freq[(s.kind, tf)] += 1
                ex = examples.setdefault(s.kind, [])
                if len(ex) < 3 and s.index >= len(bars) - 120:
                    ex.append(f"- **{coin} {tf}**, candle {S.bar_time(s.t)}: {s.text}  \n  Check: {evidence(s, bars)}")
    print("## Examples\n")
    for kind in S.KINDS:
        print(f"### {S.KINDS[kind].title}\n")
        print("\n".join(examples.get(kind, ["- No example in these coins' recent candles."])) + "\n")
    print("## How often each signal fires (per 100 closed candles, these coins)\n")
    print("| Signal | 1h | 4h | 1d |\n|---|---|---|---|")
    for kind in S.KINDS:
        cells = [f"{freq[(kind, tf)] / bars_total[tf] * 100:.1f}" if bars_total[tf] else "–" for tf in TFS]
        print(f"| {S.KINDS[kind].title} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main(sys.argv[1:] or ["BTC", "ETH", "SOL", "XRP", "DOGE", "BNB", "ADA", "LINK"])
